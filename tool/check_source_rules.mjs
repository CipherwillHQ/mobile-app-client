// Enforces the repository's handwritten-file readability limits.
// Owns introductory comments, line caps and formatting checks.
// Does not build artifacts or run authentication flows.
import {readFileSync,readdirSync} from 'node:fs';
import {resolve,dirname,isAbsolute} from 'node:path';
import {fileURLToPath} from 'node:url';
import {execFileSync} from 'node:child_process';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
function walk(directory){return readdirSync(directory,{withFileTypes:true}).flatMap(entry=>entry.isDirectory()?walk(resolve(directory,entry.name)):[resolve(directory,entry.name)]);}
const files=['lib','test'].flatMap(name=>walk(resolve(root,name))).filter(name=>name.endsWith('.dart'));
for(const file of files){
  const source=readFileSync(file,'utf8');
  if(file.endsWith('firebase_options.dart') && source.startsWith('// File generated by FlutterFire CLI.'))continue;
  if(source.trimEnd().split(/\r?\n/).length>=200)throw Error('File cap exceeded: '+file);
  if(!/^\/\/.*\r?\n\/\/.*\r?\n\/\/.*/.test(source))throw Error('Introductory comment missing: '+file);
}
if(process.argv.includes('--format')){
  let command=process.env.DART_COMMAND || (process.platform==='win32'?'dart.bat':'dart');
  if(process.platform==='win32' && command.endsWith('.bat')){
    const batch=isAbsolute(command)?command:execFileSync('where.exe',[command],{encoding:'utf8'}).trim().split(/\r?\n/)[0];
    command=resolve(dirname(batch),'cache/dart-sdk/bin/dart.exe');
  }
  for(let offset=0;offset<files.length;offset+=10)execFileSync(command,['format','--output=none','--set-exit-if-changed',...files.slice(offset,offset+10)],{stdio:'inherit'});
}
console.log('Handwritten source rules passed.');
